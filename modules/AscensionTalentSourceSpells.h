inline void GrantSourceSpellsForTalent(Player* player, uint32_t talentId)
{
    if (!player || talentId < FirstTalentId || talentId >= FirstTalentId + TalentCount) return;
    uint32_t const index = talentId - FirstTalentId;
    uint8_t const spec = player->GetActiveSpec();
    uint8_t const specMask = uint8_t(1u << spec);
    TalentEntry const* talent = sTalentStore.LookupEntry(talentId);
    if (!talent)
    {
        LOG_ERROR("scripts.ascension.talents", "Missing Talent.dbc row {} for source-spell grant", talentId);
        return;
    }
    for (uint32_t rank = 0; rank < MaxTalentRanks; ++rank)
        if (talent->RankID[rank] != TalentMarkerIds[index][rank])
        {
            LOG_ERROR("scripts.ascension.talents", "Talent.dbc and source mapping disagree for talent {} rank {}", talentId, rank + 1);
            return;
        }

    int32_t selectedRank = -1;
    for (uint32_t rank = 0; rank < MaxTalentRanks; ++rank)
        if (TalentMarkerIds[index][rank] && player->HasTalent(TalentMarkerIds[index][rank], spec))
            selectedRank = int32_t(rank);
    if (selectedRank < 0)
        return;

    if (TalentUsesSourceRanks[index] && selectedRank > 0)
    {
        uint32_t const selectedSpell = TalentSpellIds[index][selectedRank];
        if (!selectedSpell || !sSpellMgr->GetSpellInfo(selectedSpell))
        {
            LOG_ERROR("scripts.ascension.talents", "Missing source spell for talent {} rank {}", talentId, selectedRank + 1);
            return;
        }
        // Remove prior owned ranks when the source spell ranks are not linked.
        for (int32_t rank = 0; rank < selectedRank; ++rank)
        {
            uint32_t const previousSpell = TalentSpellIds[index][rank];
            if (!previousSpell || sSpellMgr->GetFirstSpellInChain(previousSpell) ==
                                      sSpellMgr->GetFirstSpellInChain(selectedSpell))
                continue;
            if (CharacterDatabase.Query("SELECT spell_id FROM character_class_talent_source_spells WHERE guid = {} AND spec = {} AND spell_id = {}",
                                        player->GetGUID().GetCounter(), spec, previousSpell))
            {
                player->removeSpell(previousSpell, specMask, false);
                CharacterDatabase.DirectExecute("DELETE FROM character_class_talent_source_spells WHERE guid = {} AND spec = {} AND spell_id = {}",
                                                player->GetGUID().GetCounter(), spec, previousSpell);
            }
        }
    }

    for (uint32_t sourceRank = 0; sourceRank < MaxTalentRanks; ++sourceRank)
    {
        if (TalentUsesSourceRanks[index] && sourceRank != uint32_t(selectedRank))
            continue;
        uint32_t const spellId = TalentSpellIds[index][sourceRank];
        if (!spellId)
            continue;
        auto const& spells = player->GetSpellMap();
        auto const found = spells.find(spellId);
        if (found != spells.end() && found->second->State != PLAYERSPELL_REMOVED && (found->second->specMask & specMask))
            continue;
        if (!sSpellMgr->GetSpellInfo(spellId))
        {
            LOG_ERROR("scripts.ascension.talents", "Official talent spell {} is absent from Spell.dbc (talent {})", spellId, talentId);
            continue;
        }
        player->learnSpell(spellId);
        bool const sendLearnPacket = player->addSpell(spellId, specMask, true);
        auto const learned = player->GetSpellMap().find(spellId);
        if (learned != player->GetSpellMap().end() && learned->second->State != PLAYERSPELL_REMOVED &&
            (learned->second->specMask & specMask))
        {
            if (sendLearnPacket)
                player->SendLearnPacket(spellId, true);
            CharacterDatabase.DirectExecute("INSERT IGNORE INTO character_class_talent_source_spells (guid, spec, spell_id) VALUES ({}, {}, {})", player->GetGUID().GetCounter(), spec, spellId);
        }
        else
            LOG_ERROR("scripts.ascension.talents", "Failed to grant talent spell {} (talent {})", spellId, talentId);
    }
}

inline void SyncActiveSpec(Player* player, uint32_t firstTalent, uint32_t treeCount = 3)
{
    if (!player) return;
    for (uint32_t tree = 0; tree < treeCount; ++tree)
        for (uint32_t node = 0; node < TalentNodeCountsByTree[firstTalent + tree]; ++node)
        {
            uint32_t const talentId = TalentIdsByTree[firstTalent + tree][node];
            if (!talentId) continue;
            uint32_t const index = talentId - FirstTalentId;
            bool selected = false;
            for (uint32_t rank = 0; rank < MaxTalentRanks; ++rank)
                selected = selected || player->HasTalent(TalentMarkerIds[index][rank], player->GetActiveSpec());
            if (selected) GrantSourceSpellsForTalent(player, talentId);
        }
}

inline void RemoveAcquiredSourceSpellsForActiveSpec(Player* player)
{
    if (!player) return;
    uint32_t const guid = player->GetGUID().GetCounter();
    uint8_t const spec = player->GetActiveSpec();
    if (QueryResult result = CharacterDatabase.Query("SELECT spell_id FROM character_class_talent_source_spells WHERE guid = {} AND spec = {}", guid, spec))
        do
        {
            Field* fields = result->Fetch();
            uint32_t const spellId = fields[0].Get<uint32_t>();
            auto const found = player->GetSpellMap().find(spellId);
            // A source spell later trained for every spec remains trainer-owned after a reset.
            if (found != player->GetSpellMap().end() && found->second->specMask != SPEC_MASK_ALL)
                player->removeSpell(spellId, uint8_t(1u << spec), false);
        } while (result->NextRow());
    CharacterDatabase.DirectExecute("DELETE FROM character_class_talent_source_spells WHERE guid = {} AND spec = {}", guid, spec);
}
